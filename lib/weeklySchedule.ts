/**
 * يبحث عن الأسبوع الذي يقع فيه التاريخ المعطى
 * يقارن بتاريخ البداية (الأحد) — الأسبوع يمتد حتى الخميس (4 أيام بعد البداية)
 */
export function getWeekInfo(sundayDate: string): WeekInfo | null {
  for (const w of ACADEMIC_WEEKS) {
    const start = new Date(w.start);
    const end   = new Date(w.start);
    end.setDate(end.getDate() + 4); // الخميس
    const d = new Date(sundayDate);
    if (d >= start && d <= end) return w;
  }
  return null;
}
