// تُرجع صفوف المرحلة المناسبة حسب اسم/مرحلة المدرسة
export function gradesForLevel(level?: string): string[] {
  const s = level ?? "";
  if (s.includes("ابتدائ") || s.includes("إبتدائ")) return G_PRIMARY;
  if (s.includes("اعداد") || s.includes("إعداد")) return G_PREP;
  if (s.includes("ثانو")) return G_SEC;
  if (s.includes("نموذج")) return [...G_PRIMARY, ...G_PREP]; // النموذجية غالباً ابتدائي + إعدادي
  return ALL_GRADES; // مشترك أو غير محدد
}

