export interface TeachingScoreEntry {
  standard: string;
  evaluator1: number[];
  evaluator2: number[];
  evaluator3: number[];
}

export interface CoordinationScoreEntry {
  standard: string;
  evaluator1: number[];
  evaluator2: number[];
}

export function buildTeachingScores(variantId: string): TeachingScoreEntry[] {
  const has3 = variantId !== "1-3";
  return TEACHING_STANDARDS.map((s) => ({
    standard: s.standard,
    evaluator1: new Array(s.indicators.length).fill(0),
    evaluator2: new Array(s.indicators.length).fill(0),
    evaluator3: has3 ? new Array(s.indicators.length).fill(0) : [],
  }));
}

export function buildCoordinationScores(): CoordinationScoreEntry[] {
  return COORDINATION_STANDARDS.map((s) => ({
    standard: s.standard,
    evaluator1: new Array(s.indicators.length).fill(0),
    evaluator2: new Array(s.indicators.length).fill(0),
  }));
}

