// ── حساب النسب والمجاميع ────────────────────────────────────────────────────
export function calcStandardAvg(entry: TeachingScoreEntry | CoordinationScoreEntry, numEvaluators: number): number {
  const e1 = entry.evaluator1;
  const e2 = entry.evaluator2;
  const e3 = "evaluator3" in entry ? entry.evaluator3 : [];
  const allScores = numEvaluators === 3 ? [...e1, ...e2, ...e3] : [...e1, ...e2];
  const filled = allScores.filter((s) => s > 0);
  if (filled.length === 0) return 0;
  const perEval = numEvaluators === 3
    ? [calcEvalAvg(e1), calcEvalAvg(e2), calcEvalAvg(e3)]
    : [calcEvalAvg(e1), calcEvalAvg(e2)];
  const filledEvals = perEval.filter((s) => s > 0);
  if (filledEvals.length === 0) return 0;
  return filledEvals.reduce((a, b) => a + b, 0) / filledEvals.length;
}

function calcEvalAvg(scores: number[]): number {
  const filled = scores.filter((s) => s > 0);
  if (filled.length === 0) return 0;
  return filled.reduce((a, b) => a + b, 0);
}

export function calcPercentage(scores: TeachingScoreEntry[] | CoordinationScoreEntry[], standards: LicenseStandard[], numEvaluators: number): number {
  let totalAchieved = 0;
  let totalMax = 0;
  for (let i = 0; i < standards.length; i++) {
    const entry = scores[i];
    if (!entry) continue;
    const maxPerEval = standards[i].maxScore;
    const e1Sum = calcEvalAvg(entry.evaluator1);
    const e2Sum = calcEvalAvg(entry.evaluator2);
    const e3Sum = "evaluator3" in entry && numEvaluators === 3 ? calcEvalAvg(entry.evaluator3) : 0;
    const numFilledEvals = [e1Sum, e2Sum, ...(numEvaluators === 3 ? [e3Sum] : [])].filter((s) => s > 0).length;
    if (numFilledEvals === 0) continue;
    const avgScore = (e1Sum + e2Sum + (numEvaluators === 3 ? e3Sum : 0)) / numFilledEvals;
    const maxPossible = maxPerEval; // already sum-based
    totalAchieved += avgScore;
    totalMax += maxPossible;
  }
  if (totalMax === 0) return 0;
  return Math.round((totalAchieved / totalMax) * 100 * 10) / 10;
}

